"""Chaining Kaggle sessions: the next session starts by itself when one ends, the data download runs on a CPU notebook and then starts the
GPU notebook, and when the weekly GPU quota is used up a CPU "waiter" notebook sleeps until the reset and then starts the GPU notebook.

    kind "cpu_data"   a CPU-only notebook (no GPU quota used). Runs the data stage; when it is DONE it starts the GPU notebook.
    kind "gpu"        the training notebook. When a session ends PAUSED (time budget used up, state saved) it starts the next GPU session.
                      When it ends NO_QUOTA (or the next session would not get enough quota) it starts the waiter, if the reset time is known.
    kind "wait"       a CPU-only notebook that sleeps until the quota reset (at most 11 h per notebook, then it starts another waiter) and
                      then starts the GPU notebook.

How a notebook starts another one: it writes a notebook folder (kernel-metadata.json + a one-cell run.ipynb) and runs the official
``kaggle kernels push -p <folder>``, which creates a new version of that notebook and runs it. The generated cell clones this repository
and calls scripts/kaggle_run.py with the same arguments as the current session (chain counter + 1). No secret is ever written into the
pushed files: the new notebook reads HF_TOKEN / KAGGLE_* / GITHUB_TOKEN from the Kaggle secrets attached to it (attach them once in the
notebook editor, Add-ons > Secrets).

Safeguards (a bug must never loop):
    * at most ``max_chain`` chained starts (default 40);  * a crash (CRASHED) never chains;  * a PAUSED session that made no progress
    (under 6 minutes) does not chain;  * before a GPU start the quota is checked again (no start without a useful budget);
    * kill switch: an empty file named ``.stop_chain`` in the Hugging Face run repo (Files > Add file) stops the chain at the next step.
The weekly quota itself is still enforced by kaggle.py (budget, ledger, NO_QUOTA), so chaining cannot use more GPU time than the quota.
"""
import json
import os
import subprocess
import sys
import time
from dataclasses import dataclass
from pathlib import Path

from . import kaggle

DEFAULT_REPO = "https://github.com/MANOFHATERS/sphota.git"
DEFAULT_MACHINE_SHAPE = "NvidiaTeslaT4"          # what a 3-year-old kaggle-cli issue reports for "GPU T4 x2"; "" omits the field
MAX_WAIT_HOURS = 11.0                            # one waiter notebook sleeps at most this long, then starts another waiter
WAKE_MARGIN_MIN = 10.0                           # wake this long after the announced reset
MIN_PROGRESS_H = 0.1                             # a PAUSED session shorter than this made no progress
STOP_FILE = ".stop_chain"
KINDS = ("cpu_data", "gpu", "wait")
CHAIN_FLAGS = ("--chain-kind", "--chain-count", "--wait-until", "--quota-hours")      # set by the chain for the next kernel


@dataclass
class ChainConfig:
    owner: str = ""
    gpu_slug: str = "sphota-train"
    cpu_slug: str = "sphota-data"
    wait_slug: str = "sphota-wait"
    kind: str = "gpu"
    count: int = 0
    max_chain: int = 40
    repo: str = DEFAULT_REPO
    machine_shape: str = DEFAULT_MACHINE_SHAPE
    reset: tuple = None                          # (weekday with Monday = 0, UTC hour) of the weekly quota reset
    wait_until: float = None
    weekly_quota: float = None
    quota_hours: float = None
    hours_limit: float = kaggle.DEFAULT_HOURS
    dead_hours: float = None                     # hours a cancelled / killed session is assumed to have used (see kaggle.used_quota_hours)


# ------------------------------------------------------------------------------------------------ files of a notebook
def title_for(slug):
    """Kaggle derives the notebook slug from its title, so the title is the slug with spaces."""
    return slug.replace("-", " ")


def kernel_metadata(owner, slug, gpu, internet=True, machine_shape=DEFAULT_MACHINE_SHAPE):
    """The kernel-metadata.json of a private notebook (field names and string booleans as in the kaggle-cli docs)."""
    m = {"id": f"{owner}/{slug}", "title": title_for(slug), "code_file": "run.ipynb", "language": "python", "kernel_type": "notebook",
         "is_private": "true", "enable_gpu": "true" if gpu else "false", "enable_tpu": "false",
         "enable_internet": "true" if internet else "false", "dataset_sources": [], "competition_sources": [],
         "kernel_sources": [], "model_sources": []}
    if gpu and machine_shape:
        m["machine_shape"] = machine_shape
    return m


def run_source(repo, argv):
    """The code of the one notebook cell: clone / update the repository and run the driver with ``argv``. Contains no secret (a
    GITHUB_TOKEN secret, if the repository is private, is read at run time)."""
    return (
        "# generated by truesight/chain.py\n"
        "import json, os, subprocess, sys\n"
        f"REPO, DIR, ARGS = {repo!r}, 'sphota', json.loads({json.dumps(argv)!r})\n"
        "try:\n"
        "    from kaggle_secrets import UserSecretsClient\n"
        "    tok = UserSecretsClient().get_secret('GITHUB_TOKEN')\n"
        "    if tok and REPO.startswith('https://'):\n"
        "        REPO = REPO.replace('https://', f'https://{tok}@', 1)\n"
        "except Exception:\n"
        "    pass\n"
        "if os.path.exists(DIR):\n"
        "    subprocess.run(['git', '-C', DIR, 'pull', '--ff-only'], check=False)\n"
        "else:\n"
        "    subprocess.run(['git', 'clone', REPO, DIR], check=True)\n"
        "sys.exit(subprocess.run([sys.executable, DIR + '/scripts/kaggle_run.py'] + ARGS).returncode)\n")


def notebook_json(source):
    return {"cells": [{"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [], "source": source.splitlines(True)}],
            "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"}},
            "nbformat": 4, "nbformat_minor": 5}


def write_kernel(folder, owner, slug, argv, gpu, repo=DEFAULT_REPO, machine_shape=DEFAULT_MACHINE_SHAPE):
    """Write the notebook folder for ``kaggle kernels push -p``. Returns the folder path."""
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "kernel-metadata.json").write_text(json.dumps(kernel_metadata(owner, slug, gpu, machine_shape=machine_shape), indent=2))
    (folder / "run.ipynb").write_text(json.dumps(notebook_json(run_source(repo, list(argv))), indent=1))
    return folder


def have_kaggle_credentials(env=None, home=None):
    """Can the kaggle CLI log in? (KAGGLE_USERNAME + KAGGLE_KEY, KAGGLE_API_TOKEN, or a kaggle.json file)."""
    env = os.environ if env is None else env
    if (env.get("KAGGLE_USERNAME") and env.get("KAGGLE_KEY")) or env.get("KAGGLE_API_TOKEN"):
        return True
    d = Path(env.get("KAGGLE_CONFIG_DIR") or (Path(home) if home else Path.home()) / ".kaggle")
    return (d / "kaggle.json").exists() or (d / "access_token").exists()


def kaggle_env(base=None):
    """Environment for the kaggle CLI: credentials come from the Kaggle secrets that load_kaggle_secrets() copied into the environment
    (KAGGLE_USERNAME + KAGGLE_KEY, or KAGGLE_API_TOKEN), or from ~/.kaggle/kaggle.json."""
    return dict(base if base is not None else os.environ)


_CLI_READY = {"done": False}


def ensure_cli(env=None, run=subprocess.run):
    """The new-style access token (KAGGLE_API_TOKEN, starts with KGAT_) needs a recent kaggle CLI, and the one preinstalled in a notebook can
    be older: upgrade it once (best effort) before the first push. Does nothing without KAGGLE_API_TOKEN."""
    env = os.environ if env is None else env
    if _CLI_READY["done"] or not env.get("KAGGLE_API_TOKEN"):
        return False
    _CLI_READY["done"] = True
    try:
        run([sys.executable, "-m", "pip", "install", "-q", "-U", "kaggle"], capture_output=True, timeout=300)
    except Exception:
        return False
    return True


def push_kernel(folder, run=subprocess.run, env=None, kaggle_cmd=("kaggle",)):
    """``kaggle kernels push -p <folder>`` (creates a new version of the notebook and runs it). Returns (ok, output)."""
    if run is subprocess.run:                                         # a real push (tests pass a fake runner)
        ensure_cli()
    try:
        r = run([*kaggle_cmd, "kernels", "push", "-p", str(folder)], capture_output=True, text=True, env=env or kaggle_env(), timeout=300)
    except (OSError, subprocess.SubprocessError) as e:
        return False, f"{type(e).__name__}: {e}"
    out = ((r.stdout or "") + (r.stderr or "")).strip()
    return r.returncode == 0 and "error" not in out.lower(), out


# ------------------------------------------------------------------------------------------------ arguments of the next notebook
def strip_flag(argv, flag, has_value=True):
    """``argv`` without ``flag`` (and its value / ``flag=value``)."""
    out, skip = [], False
    for a in argv:
        if skip:
            skip = False
            continue
        if a == flag:
            skip = has_value
            continue
        if a.startswith(flag + "="):
            continue
        out.append(a)
    return out


def next_argv(argv, kind, count, quota_hours=None, wait_until=None, drop_stages=False):
    """The driver arguments for the next notebook: the current ones with the chain flags replaced (and ``--stages`` dropped when the
    data notebook hands over to the GPU notebook, which runs every stage)."""
    out = argv
    for f in CHAIN_FLAGS:
        out = strip_flag(out, f)
    if drop_stages:
        out = strip_flag(out, "--stages")
    out = out + ["--chain-kind", kind, "--chain-count", str(count)]
    if quota_hours is not None:
        out += ["--quota-hours", f"{quota_hours:.3f}"]
    if wait_until is not None:
        out += ["--wait-until", f"{wait_until:.0f}"]
    return out


# ------------------------------------------------------------------------------------------------ what comes next
def decide(kind, status, count, max_chain, can_wait, progress_h=None, stopped=False):
    """The next step after a session. Returns (action, reason); action is "gpu", "cpu_data", "wait" or "stop". Pure function."""
    if stopped:
        return "stop", f"kill switch: {STOP_FILE} exists in the run repo"
    if count + 1 > max_chain:
        return "stop", f"chain limit reached ({max_chain} chained starts)"
    if status == kaggle.BUSY:
        return "stop", "another GPU session of this run is already running: not chaining"
    if status == kaggle.CRASHED:
        return "stop", "the session crashed: not chaining (fix the cause, push, start it by hand)"
    if kind == "cpu_data":
        if status == kaggle.DONE:
            return "gpu", "data is ready: starting the GPU notebook"
        if status == kaggle.PAUSED:
            return "cpu_data", "data session paused at its time limit: continuing the data notebook"
        return "stop", f"data notebook ended with {status}"
    if kind == "gpu":
        if status == kaggle.DONE:
            return "stop", "ALL STAGES FINISHED: nothing more to run"
        if status == kaggle.PAUSED:
            if progress_h is not None and progress_h < MIN_PROGRESS_H:
                return "stop", f"the session paused after {progress_h * 60:.0f} min without progress: not chaining"
            return "gpu", "session paused at its budget (state saved): starting the next session"
        if status == kaggle.NO_QUOTA:
            return ("wait", "weekly GPU quota used up: waiting for the reset on a CPU notebook") if can_wait else \
                   ("stop", "weekly GPU quota used up and the reset time is unknown (--quota-reset-dow): start the next session by hand")
    return "stop", f"nothing to chain after {kind}/{status}"


def stop_requested(spec, exp_dir=None):
    """Is the kill-switch file present in the run repo? Looks in the already pulled run folder first, then asks the storage."""
    if exp_dir is not None and (Path(exp_dir) / STOP_FILE).exists():
        return True
    try:
        kind, target = spec.partition(":")[0], spec.partition(":")[2]
        if kind == "dir":
            return (Path(target) / STOP_FILE).exists()
        from huggingface_hub import HfApi
        return bool(HfApi(token=os.environ.get("HF_TOKEN")).file_exists(target, STOP_FILE, repo_type="model"))
    except Exception:
        return False


def _slug(cfg, kind):
    return {"gpu": cfg.gpu_slug, "cpu_data": cfg.cpu_slug, "wait": cfg.wait_slug}[kind]


def start_kernel(cfg, kind, argv, workdir, push=push_kernel, log=kaggle.log):
    """Write and push the notebook ``kind`` with ``argv``. Returns True if Kaggle accepted it."""
    folder = write_kernel(Path(workdir) / _slug(cfg, kind), cfg.owner, _slug(cfg, kind), argv, gpu=(kind == "gpu"), repo=cfg.repo,
                          machine_shape=cfg.machine_shape)
    ok, out = push(folder)
    log(f"[chain] push {cfg.owner}/{_slug(cfg, kind)}: {'started' if ok else 'FAILED'}: {out[-300:]}")
    return ok


def quota_left_h(cfg, exp_dir, now=None, quota_hours_next=None):
    """The session budget (hours) the next GPU session would get, from the ledger / the remaining explicit quota."""
    now = time.time() if now is None else now
    b, _ = kaggle.plan_budget(cfg.hours_limit, quota_hours_next if quota_hours_next is not None else cfg.quota_hours, cfg.weekly_quota,
                              kaggle.read_ledger(exp_dir), now, reset=cfg.reset, dead_hours=cfg.dead_hours)
    return b


def after_session(cfg, argv, status, exp_dir, spec, workdir, push=push_kernel, now=None, last=None, log=kaggle.log, ready=True):
    """Called by kaggle_run.py when a session has ended and its state is saved. Starts the next notebook if the chain should go on.
    Returns the action taken ("gpu", "cpu_data", "wait" or "stop")."""
    now = time.time() if now is None else now
    last = kaggle.LAST_SESSION if last is None else last
    used = float(last.get("hours_used", 0.0)) if last.get("gpu") or cfg.kind == "cpu_data" else None
    can_wait = cfg.reset is not None and cfg.weekly_quota is not None
    action, why = decide(cfg.kind, status, cfg.count, cfg.max_chain, can_wait, used, stop_requested(spec, exp_dir))
    if action == "gpu" and cfg.kind == "cpu_data" and not ready:                       # DONE, but nothing was downloaded
        action, why = "stop", "the data notebook finished but data/raw has no images: not starting the GPU notebook (check the log above)"
    q_next = None
    if cfg.kind == "gpu" and cfg.quota_hours is not None:                  # explicit mode: what is left after this session
        q_next = max(0.0, cfg.quota_hours - float(last.get("hours_used", 0.0)))
    if action == "gpu" and quota_left_h(cfg, exp_dir, now, q_next) < kaggle.MIN_USEFUL_H and cfg.kind in ("gpu", "cpu_data"):
        action, why = ("wait", "not enough GPU quota left for another session: waiting for the reset") if can_wait else \
                      ("stop", "not enough GPU quota left for another session and the reset time is unknown: stopping")
    log(f"[chain] {cfg.kind}/{status} -> {action}: {why}")
    if action == "stop":
        return action
    count = cfg.count + 1
    if action == "gpu":
        nxt = next_argv(argv, "gpu", count, quota_hours=q_next if cfg.kind == "gpu" else None, drop_stages=(cfg.kind == "cpu_data"))
    elif action == "cpu_data":
        nxt = next_argv(argv, "cpu_data", count)
    else:                                                                   # wait for the reset
        wake = kaggle.next_reset(now, *cfg.reset) + WAKE_MARGIN_MIN * 60
        nxt = next_argv(argv, "wait", count, wait_until=wake)
    ok = start_kernel(cfg, action, nxt, workdir, push, log)
    return action if ok else "stop"


# ------------------------------------------------------------------------------------------------ the waiter notebook
def wait_until(ts, max_hours=MAX_WAIT_HOURS, sleep=time.sleep, now=time.time, step_s=60.0):
    """Sleep until the epoch time ``ts`` (at most ``max_hours``). Returns True if ``ts`` was reached, False if the limit came first."""
    end = now() + max_hours * 3600.0
    while now() < ts:
        if now() >= end:
            return False
        sleep(min(step_s, max(0.0, ts - now()), max(0.0, end - now())))
    return True


def run_wait(cfg, argv, spec, workdir, push=push_kernel, sleep=time.sleep, now=time.time, log=kaggle.log):
    """The waiter notebook: sleep until the quota reset, then start the GPU notebook (or another waiter if the reset is still far).
    Returns "gpu", "wait" or "stop"."""
    ts = cfg.wait_until or now()
    log(f"[chain] waiting for the quota reset at {time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime(ts))}")
    reached = wait_until(ts, sleep=sleep, now=now)
    count = cfg.count + 1
    if stop_requested(spec):
        log(f"[chain] kill switch ({STOP_FILE}) found: stopping")
        return "stop"
    if count > cfg.max_chain:
        log(f"[chain] chain limit reached ({cfg.max_chain}): stopping")
        return "stop"
    kind = "gpu" if reached else "wait"
    nxt = next_argv(argv, kind, count, wait_until=None if reached else ts)
    ok = start_kernel(cfg, kind, nxt, workdir, push, log)
    return kind if ok else "stop"
